"""Run WMLES of the A-airfoil at the Tamaki-Kawai reference conditions.

    python -m examples.airfoil_wmles [out/a_airfoil.p3d] --steps 0

The reference flow is Mach 0.15, Re_c=1e7, alpha=13.3 degrees. A zero-step
run assembles and reports the case; positive --steps advances the solver.
"""
import argparse
import time

from wmles.airfoil_case import (
    ALPHA_DEG,
    MACH_INF,
    RE_CHORD,
    build_case,
    describe_case,
    initial_state,
)
from wmles.backend import HAS_JAX, device_info, xp
from wmles.io_wall_loads import WallLoadCSVWriter


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("grid", nargs="?", default="out/a_airfoil.p3d",
                        help="four-block grid generated by wmles.airfoil_grid")
    parser.add_argument("--mach", type=float, default=MACH_INF)
    parser.add_argument("--re", type=float, default=RE_CHORD,
                        help="chord Reynolds number")
    parser.add_argument("--alpha", type=float, default=ALPHA_DEG,
                        help="geometric incidence in degrees")
    parser.add_argument("--temperature", type=float, default=200.0,
                        help="free-stream temperature [K] (reference-scale assumption)")
    parser.add_argument("--pressure", type=float, default=101_325.0,
                        help="free-stream pressure [Pa] (reference-scale assumption)")
    parser.add_argument("--n-match", type=int, default=1,
                        help="wall-model sampling cell counted from the wall")
    parser.add_argument("--cfl", type=float, default=0.5)
    parser.add_argument("--steps", type=int, default=0)
    parser.add_argument("--vtu", type=int, default=0,
                        help="write VTU every N steps (requires PyVista)")
    args = parser.parse_args()
    if args.steps < 0 or args.vtu < 0:
        parser.error("--steps and --vtu must be non-negative")
    if args.n_match < 1:
        parser.error("--n-match must be at least 1")

    mesh, solver, props = build_case(
        args.grid, mach=args.mach, reynolds=args.re, alpha_deg=args.alpha,
        T_inf=args.temperature, p_inf=args.pressure,
        n_match=args.n_match, cfl=args.cfl,
    )
    print(f"backend={'jax' if HAS_JAX else 'numpy'} device={device_info()}")
    print(describe_case(mesh, props))
    if args.steps == 0:
        return

    wall_writer = WallLoadCSVWriter("out/a_airfoil_wmles/forces_moments.csv", (0.25, 0.0, 0.0))
    state = initial_state(solver, props)
    time_elapsed, writer = 0.0, None
    for step in range(1, args.steps + 1):
        start = time.perf_counter()
        dt = solver.max_dt(state)
        state = solver.advance(state, dt, time_elapsed)
        time_elapsed += float(dt)
        if HAS_JAX:
            for block_state in state:
                block_state.block_until_ready()
        if args.vtu and step % args.vtu == 0:
            from wmles.io_vtk import write_case
            writer = write_case(
                mesh, solver, state, step, time_elapsed,
                "out/a_airfoil_wmles", writer=writer,
            )
        #if step % max(1, args.steps // 10) == 0 or step == 1:
        if step % 1000 == 0 or step == 1:
            rho_min = min(
                float(xp.min(block.interior(q[0])))
                for block, q in zip(mesh.blocks, state)
            )
            ctu = time_elapsed * props["U_inf"] / props["chord"]
            print(f"step={step:6d} t={time_elapsed:.4e} "
                  f"dt={float(dt):.3e} rho_min={rho_min:.6g} "
                  f"ctu={ctu:.6f} "
                  f"step_time={time.perf_counter() - start:.3f}s")
            wall_writer.write(step, time_elapsed, solver.wall_loads(state))


if __name__ == "__main__":
    main()
