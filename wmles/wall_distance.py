"""Wall distance for every (ghost-extended) cell of a finalized `Mesh`, for RANS/DES models.

Host-side, computed once before the solver is built.  Wall faces are the block faces whose
BC has `is_wall = True` (`NoSlipWall`, `WallModel`).  Each wall face is split into two
triangles; the distance of a cell centre is the exact distance to the nearest triangle.  The
nearest face is searched among the `k` faces whose centres are closest (cKDTree) and, by
default, certified: points for which a farther face could still be closer (elongated or very
unequal faces) are re-searched with more candidates until the result is provably exact.
Periodic
connections are honoured by replicating the wall with the translations of the mesh's
periodic interfaces, so ghost cells across a periodic boundary see the periodic wall.

The distance is unsigned: ghost cells mirrored behind a wall get the distance to it.

    mesh.finalize()
    attach_wall_distance(mesh)      # before building the Solver; fills Geom.dist
"""
from itertools import product

import numpy as np
from scipy.spatial import cKDTree

from .backend import asarray
from .mesh import Interface


def _dot(a, b):
    return np.einsum("...i,...i->...", a, b)


def point_triangle_distance2(p, a, b, c):
    """Squared distance from points p to triangles (a, b, c); arrays broadcast over leading axes
    (last axis = xyz).  Closest-point regions follow Ericson, Real-Time Collision Detection."""
    ab, ac = b - a, c - a
    ap, bp, cp = p - a, p - b, p - c
    d1, d2 = _dot(ab, ap), _dot(ac, ap)
    d3, d4 = _dot(ab, bp), _dot(ac, bp)
    d5, d6 = _dot(ab, cp), _dot(ac, cp)
    vc, vb, va = d1 * d4 - d3 * d2, d5 * d2 - d1 * d6, d3 * d6 - d5 * d4
    with np.errstate(divide="ignore", invalid="ignore"):
        den = va + vb + vc
        q = a + ab * (vb / den)[..., None] + ac * (vc / den)[..., None]
        for cond, pt in (
            ((va <= 0) & (d4 - d3 >= 0) & (d5 - d6 >= 0),
             b + (c - b) * ((d4 - d3) / ((d4 - d3) + (d5 - d6)))[..., None]),
            ((vb <= 0) & (d2 >= 0) & (d6 <= 0), a + ac * (d2 / (d2 - d6))[..., None]),
            ((d6 >= 0) & (d5 <= d6), c),
            ((vc <= 0) & (d1 >= 0) & (d3 <= 0), a + ab * (d1 / (d1 - d3))[..., None]),
            ((d3 >= 0) & (d4 <= d3), b),
            ((d1 <= 0) & (d2 <= 0), a),
        ):
            q = np.where(cond[..., None], pt, q)
    q = np.where(np.all(np.isfinite(q), axis=-1)[..., None], q, a)      # degenerate triangle
    return _dot(p - q, p - q)


def wall_patches(mesh):
    """Interior node planes (3, n1, n2) of every wall face of the mesh."""
    out = []
    for blk in mesh.blocks:
        for (axis, side), bc in blk.faces.items():
            if getattr(bc, "is_wall", False):
                out.append(np.take(blk.x_int, 0 if side == 0 else -1, axis=axis + 1))
    return out


def periodic_translations(mesh):
    """All translation vectors generated by the mesh's periodic interfaces (incl. zero)."""
    vecs = []
    for blk in mesh.blocks:
        for f in blk.faces.values():
            if isinstance(f, Interface) and np.any(f.shift != 0.0):
                v = np.where(np.abs(f.shift) < 1e-12 * (1.0 + np.abs(f.shift).max()), 0.0, f.shift)
                first = v[np.nonzero(v)[0][0]]
                v = v if first > 0 else -v
                if not any(np.allclose(v, u, rtol=0.0, atol=1e-9 * (1.0 + np.abs(v).max())) for u in vecs):
                    vecs.append(v)
    return [sum((c * v for c, v in zip(coef, vecs)), np.zeros(3))
            for coef in product((-1, 0, 1), repeat=len(vecs))]


def _wall_triangles(patches, translations):
    """(centres (F,3), tri_a, tri_b, tri_c each (F,2,3)) of all wall quads, replicated."""
    cents, A, B, C = [], [], [], []
    for P in patches:
        c00, c10 = P[:, :-1, :-1].reshape(3, -1).T, P[:, 1:, :-1].reshape(3, -1).T
        c01, c11 = P[:, :-1, 1:].reshape(3, -1).T, P[:, 1:, 1:].reshape(3, -1).T
        for t in translations:
            cents.append(0.25 * (c00 + c10 + c01 + c11) + t)
            A.append(np.stack([c00, c00], axis=1) + t)
            B.append(np.stack([c10, c11], axis=1) + t)
            C.append(np.stack([c11, c01], axis=1) + t)
    return np.concatenate(cents), np.concatenate(A), np.concatenate(B), np.concatenate(C)


def distance_to_patches(points, patches, translations=None, k=24, chunk=20000, exact=True, stats=None):
    """Distance of `points` (n, 3) to the wall quads of `patches` (node planes (3, n1, n2)),
    each also replicated by `translations` (default: none).

    The nearest wall face is looked for among the `k` faces with the closest centres.  With
    `exact=True` the result is certified: a face outside that set cannot be closer than
    (k-th centre distance) - (largest centre-to-corner distance of any face), so any point
    whose distance exceeds that bound is searched again with 4x more candidates until the
    bound holds or every face has been examined.  This keeps elongated or very unequal wall
    faces exact.  `stats` (a dict) receives the counts of re-searched points and the final k."""
    translations = [np.zeros(3)] if translations is None else translations
    cents, A, B, C = _wall_triangles(patches, translations)
    nf = len(cents)
    reach = max(np.linalg.norm(V - cents[:, None, :], axis=-1).max() for V in (A, B, C))
    tree = cKDTree(cents)
    points = np.asarray(points, float)
    d = np.full(len(points), np.inf)
    pending, k = np.arange(len(points)), min(int(k), nf)
    info = {"researched": 0, "k_max": k}
    while len(pending):
        step = max(256, chunk * 24 // k)
        again = []
        for s in range(0, len(pending), step):
            sel = pending[s:s + step]
            p = points[sel]
            rk, idx = tree.query(p, k=k, workers=-1)
            rk, idx = rk.reshape(len(p), k), idx.reshape(len(p), k)
            d2 = point_triangle_distance2(p[:, None, None, :], A[idx], B[idx], C[idx])
            dc = np.sqrt(d2.reshape(len(p), -1).min(axis=1))
            d[sel] = dc
            if exact and k < nf:
                again.append(sel[dc > rk[:, -1] - reach])
        pending = np.concatenate(again) if again else np.empty(0, int)
        if len(pending):
            info["researched"] += len(pending)
            k = min(4 * k, nf)
            info["k_max"] = k
    if stats is not None:
        stats.update(info)
    return d


def wall_distance(mesh, k=24, chunk=20000, exact=True, stats=None):
    """Per-block numpy arrays (Ni, Nj, Nk), ghosts included, of the distance of the cell
    centres to the nearest wall (see `distance_to_patches` for `k`, `exact`, `stats`)."""
    patches = wall_patches(mesh)
    if not patches:
        raise ValueError("mesh has no wall faces (BC.is_wall) to measure distance from")
    xc = [np.asarray(g.xc) for g in mesh.geoms]
    pts = np.concatenate([x.reshape(3, -1).T for x in xc])
    d = distance_to_patches(pts, patches, periodic_translations(mesh), k=k, chunk=chunk,
                            exact=exact, stats=stats)
    out, start = [], 0
    for x in xc:
        n = int(np.prod(x.shape[1:]))
        out.append(d[start:start + n].reshape(x.shape[1:]))
        start += n
    return out


def attach_wall_distance(mesh, **kw):
    """Store the wall distance in each block's `Geom.dist` (and `mesh.geoms`).  Call it after
    `mesh.finalize()` and before constructing a Solver (which snapshots `mesh.geoms`)."""
    dist = wall_distance(mesh, **kw)
    for blk, d in zip(mesh.blocks, dist):
        blk.geom = blk.geom._replace(dist=asarray(d))
    mesh.geoms = tuple(blk.geom for blk in mesh.blocks)
    return mesh
